// A seeded random number generator for the tests, so a draw that fails
// fails the same way on every run. The page itself uses Math.random.

// mulberry32: a small seeded generator returning floats in [0, 1).
export function seeded(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
